class TestPlants:
    def test_every_plant_has_both_pages_under_its_customer_name(self, site, psql):
        _, _, files = site
        import sys
        sys.path.insert(0, str(V2 / "server" / "bundle"))
        import portal_chrome as C
        for (k,) in psql("SELECT plant_key FROM plant WHERE active ORDER BY 1"):
            slug = C.slug(k)
            for sec in ("monitoring", "report"):
                assert f"{sec}/{slug}/index.html" in files, (k, sec)
                # the plant code is an alias that forwards to the customer page
                alias = files[f"{sec}/{k.lower()}/index.html"].read_text(encoding="utf-8")
                assert f"/{sec}/{slug}/" in alias, (k, sec)

    def test_the_dark_plant_is_shown_offline_with_its_alert(self, site):
        _, _, files = site
        s = files["monitoring/sms/index.html"].read_text(encoding="utf-8")
        assert "Plant offline" in s

    def test_fleet_page_counts_the_open_critical(self, site):
        _, _, files = site
        s = files["monitoring/index.html"].read_text(encoding="utf-8")
        m = re.search(r"(\d+)\s*<span[^>]*>critical|(\d+) critical", s)
        assert m and int(m.group(1) or m.group(2)) >= 1

    def test_live_plant_shows_its_inverters(self, site):
        _, _, files = site
        s = files["monitoring/taigene/index.html"].read_text(encoding="utf-8")
        assert "INV-01" in s and "INV-02" in s


