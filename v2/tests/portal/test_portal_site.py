class TestReports:
    def test_financial_report_carries_every_ppa_asset(self, site, psql):
        _, _, files = site
        s = files["report/financial/index.html"].read_text(encoding="utf-8")
        assert 'id="tbl_assets"' in s
        # the table is drawn in the browser from embedded daily atoms; every PPA plant must be in them
        for (k,) in psql("SELECT plant_key FROM plant WHERE portfolio = 'PPA'"):
            assert f'"{k}"' in s, k

    def test_financial_range_accepts_only_iso_dates_in_the_url(self, site):
        _, _, files = site
        s = files["report/financial/index.html"].read_text(encoding="utf-8")
        assert r"/^\d{4}-\d{2}-\d{2}$/" in s          # exactly what the browser gets

    def test_recon_csv_is_a_valid_export_with_the_closed_months(self, site, psql):
        _, _, files = site
        rows = list(csv.reader(io.StringIO(files["monitoring/recon/reconciliation.csv"].read_text(encoding="utf-8"))))
        assert len(rows) > 1 and len(rows[0]) >= 5
        n_closed = int(psql("SELECT count(*) FROM reconciliation_monthly")[0][0])
        assert len(rows) - 1 >= n_closed

    def test_every_plant_report_shows_its_production(self, site):
        _, _, files = site
        s = files["report/taigene/index.html"].read_text(encoding="utf-8")
        assert "kWh" in s and ("Taigene" in s or "TAIGENE" in s)
